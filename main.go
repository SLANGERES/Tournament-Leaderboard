package main

import (
	"log/slog"
	"net/http"
	"os"

	"github.com/SLANGERES/Tournament-Lederboard/config"
	adminHandler "github.com/SLANGERES/Tournament-Lederboard/internal/admin/handler"
	adminRepo "github.com/SLANGERES/Tournament-Lederboard/internal/admin/repository"
	adminService "github.com/SLANGERES/Tournament-Lederboard/internal/admin/service"

	userHandler "github.com/SLANGERES/Tournament-Lederboard/internal/user/handler"
	userRepo "github.com/SLANGERES/Tournament-Lederboard/internal/user/repository"
	userService "github.com/SLANGERES/Tournament-Lederboard/internal/user/service"

	tournHandler "github.com/SLANGERES/Tournament-Lederboard/internal/tournament/handler"
	tournRepo "github.com/SLANGERES/Tournament-Lederboard/internal/tournament/repository"
	tournService "github.com/SLANGERES/Tournament-Lederboard/internal/tournament/service"

	"github.com/SLANGERES/Tournament-Lederboard/internal/common/jwt"
	"github.com/SLANGERES/Tournament-Lederboard/internal/common/middleware"
	"github.com/prometheus/client_golang/prometheus/promhttp"

	_ "github.com/SLANGERES/Tournament-Lederboard/docs" // generated by swag init
	httpSwagger "github.com/swaggo/http-swagger"
)

// @title Tournament Leaderboard API
// @version 1.0
// @description API for Coding managing tournaments, admins, and users.
// @BasePath /v1
// @contact.name API Support
// @contact.email karannautiyal22@gmail.com
func main() {
	// Load config
	cnf, err := config.SetConfig()
	if err != nil {
		slog.Error("Failed to load config")
		os.Exit(1)
	}

	// Create router
	router := http.NewServeMux()

	// JWT Maker
	jwtMaker := jwt.NewJwtMaker(cnf.JwtKey)

	//--------------------------------
	// Admin Service
	//--------------------------------
	adminDB, err := adminRepo.ConfigAdminDB(cnf.AdminDB)
	if err != nil {
		slog.Error("Unable to connect to the Admin DB", "error", err)
	}
	adminSvc := adminService.NewUserService(adminDB)

	// @Summary Admin Signup
	// @Description Register a new admin
	// @Tags admin
	// @Accept json
	// @Produce json
	// @Param admin body object true "Admin signup payload"
	// @Success 201 {object} map[string]interface{}
	// @Router /admins/signup [post]
	router.HandleFunc("POST /v1/admins/signup", adminHandler.Signup(*adminSvc))

	// @Summary Admin Login
	// @Description Authenticate admin and get JWT
	// @Tags admin
	// @Accept json
	// @Produce json
	// @Param admin body object true "Admin login payload"
	// @Success 200 {object} map[string]interface{}
	// @Router /admins/login [post]
	router.HandleFunc("POST /v1/admins/login", adminHandler.Login(*adminSvc, jwtMaker))

	//--------------------------------
	// User Service
	//--------------------------------
	userDB, err := userRepo.ConfigUserStorage(cnf.UserDB)
	if err != nil {
		slog.Error("Unable to connect to the User DB", "error", err)
	}
	userSvc := userService.NewUserService(userDB)

	router.HandleFunc("POST /v1/users/signup", userHandler.SignInUser(*userSvc))
	router.HandleFunc("POST /v1/users/login", userHandler.LogInUser(*userSvc, jwtMaker))

	//--------------------------------
	// Tournament Service
	//--------------------------------
	tournDB, err := tournRepo.ConfigureTournamentStorage(cnf.AdminDB)
	if err != nil {
		slog.Error("Unable to configure Tournament DB", "error", err)
	}
	tournSvc := tournService.NewTournamentService(tournDB)

	router.Handle("POST /v1/tournaments",
		middleware.AdminMiddlewareAdmin(jwtMaker)(
			tournHandler.CreateTournament(*tournSvc),
		),
	)
	router.HandleFunc("GET /v1/tournaments/ongoing", tournHandler.GetOngoingTournament(*tournSvc))
	router.HandleFunc("GET /v1/tournaments/{id}", tournHandler.GetTournamentByID(*tournSvc))
	router.Handle("POST /v1/tournaments/addproblem/{id}",
		middleware.AdminMiddlewareAdmin(jwtMaker)(
			tournHandler.AddProblemInTournament(*tournSvc),
		),
	)
	router.Handle("POST /v1/tournaments/addtestcase/{id}",
		middleware.AdminMiddlewareAdmin(jwtMaker)(
			tournHandler.AddNewTestCase(*tournSvc),
		),
	)
	router.Handle("POST /v1/tournaments/ongoing/addparticipant/{id}",
		middleware.UserMiddlewareAdmin(jwtMaker)(
			tournHandler.AddParticipant(*tournSvc),
		),
	)
	router.HandleFunc("GET /v1/tournaments/ongoing/{id}/problem", tournHandler.GetProblem(*tournSvc))
	router.HandleFunc("GET /v1/tournaments/{id}/participants", tournHandler.GetAllParticipant(*tournSvc))

	//--------------------------------
	// Prometheus Metrics
	//--------------------------------
	router.Handle("/metrics", promhttp.Handler())

	//--------------------------------
	// Swagger Docs
	//--------------------------------
	router.Handle("/swagger/", httpSwagger.WrapHandler)

	//--------------------------------
	// Start server
	//--------------------------------
	slog.Info("Unified Server started at " + cnf.HttpServer.AdminAddress)
	err = http.ListenAndServe(cnf.HttpServer.AdminAddress, router)
	if err != nil {
		slog.Error("Server start failed", "error", err)
	}
}
